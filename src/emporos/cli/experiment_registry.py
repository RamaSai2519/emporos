"""The file registry of published experiment reports (EM-188).

    docs/strategies/experiments/
        EXP-20260924-orb-breakout-1a2b3c4d.json   the record: exact numbers, machine-readable
        EXP-20260924-orb-breakout-1a2b3c4d.md     the same report, for people
        INDEX.md / index.json                     one row per experiment, every family in one table

Reports are immutable. Publishing the same report again is a no-op; publishing a DIFFERENT report
under an id that already exists is refused, because the id names one declaration and one result:
new evidence is a new declaration, never an edit of an old verdict.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from enum import StrEnum
from pathlib import Path
from typing import Any, Protocol

from emporos.backtest.experiment_document import NOT_APPLICABLE, ExperimentDocument
from emporos.core.errors import DefinitiveError
from emporos.domain.research_experiments import ExperimentReport

DEFAULT_EXPERIMENTS_DIR = Path("docs/strategies/experiments")
INDEX_MARKDOWN = "INDEX.md"
INDEX_JSON = "index.json"


class ExperimentAlreadyPublishedError(DefinitiveError):
    """A different report is already published under this experiment id."""


class PublishOutcome(StrEnum):
    WRITTEN = "written"
    UNCHANGED = "unchanged"


class ExperimentRegistry(Protocol):
    """What a command that produces an experiment report needs: publish it, list it."""

    def publish(self, report: ExperimentReport) -> PublishOutcome: ...

    def rebuild_index(self) -> int: ...


def _json_text(document: Mapping[str, Any]) -> str:
    return json.dumps(document, indent=2) + "\n"


class ExperimentIndex:
    """One row per published experiment, read back from the published JSON, so the index can only
    say what the records say. Rows sort by family, then declaration time, then id."""

    _HEADER = (
        "id", "family", "slug", "declared", "validation", "holdout", "trades", "net P&L", "PF",
        "Sharpe", "DSR", "PBO", "outcome", "primary reasons",
    )  # fmt: skip

    def rows(self, documents: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
        rows = [self._row(d) for d in documents]
        return sorted(rows, key=lambda r: (r["family"], r["declared_at"], r["id"]))

    def markdown(self, rows: Sequence[Mapping[str, Any]]) -> str:
        lines = [
            "# Experiment index",
            "",
            "Every published experiment report, all families in one table. Generated by "
            "`emporos research experiments index`; do not edit by hand.",
            "",
            "| " + " | ".join(self._HEADER) + " |",
            "|" + "---|" * len(self._HEADER),
        ]
        for r in rows:
            cells = (
                f"[{r['id']}]({r['id']}.md)", r["family"], r["slug"], r["declared_at"][:10],
                self._span(r["validation"]), self._span(r["holdout"]), self._cell(r["trades"]),
                self._cell(r["net_pnl"]), self._cell(r["profit_factor"]), self._cell(r["sharpe"]),
                self._cell(r["deflated_sharpe"]), self._cell(r["pbo"]), r["outcome"],
                ", ".join(r["primary_reasons"]) or NOT_APPLICABLE,
            )  # fmt: skip
            lines.append("| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |")
        return "\n".join(lines) + "\n"

    @staticmethod
    def _cell(value: object) -> str:
        return NOT_APPLICABLE if value is None else str(value)

    @staticmethod
    def _span(period: Mapping[str, str] | None) -> str:
        return NOT_APPLICABLE if period is None else f"{period['first']} to {period['last']}"

    @staticmethod
    def _row(d: Mapping[str, Any]) -> dict[str, Any]:
        metrics = d["metrics"]
        reasons = d["reasons"]
        deciding = [r for r in reasons if r["outcome"] == "fail"] or [
            r for r in reasons if r["outcome"] == "unknown"
        ]
        return {
            "id": d["experiment_id"],
            "family": d["family"],
            "slug": d["slug"],
            "declared_at": d["declaration"]["declared_at"],
            "validation": d["periods"]["validation"],
            "holdout": d["periods"]["holdout"],
            "trades": metrics["trade_count"],
            "net_pnl": metrics["net_pnl"],
            "profit_factor": metrics["profit_factor"],
            "sharpe": metrics["sharpe"],
            "deflated_sharpe": metrics["deflated_sharpe"],
            "pbo": metrics["pbo"],
            "outcome": d["outcome"],
            "primary_reasons": [r["code"] or r["name"] for r in deciding],
        }


class FileExperimentRegistry:
    def __init__(
        self,
        root: Path = DEFAULT_EXPERIMENTS_DIR,
        document: ExperimentDocument | None = None,
        index: ExperimentIndex | None = None,
    ) -> None:
        self._root = root
        self._document = document or ExperimentDocument()
        self._index = index or ExperimentIndex()

    def publish(self, report: ExperimentReport) -> PublishOutcome:
        record = self._root / f"{report.experiment_id}.json"
        text = _json_text(self._document.to_json(report))
        if record.exists():
            if record.read_text(encoding="utf-8") != text:
                raise ExperimentAlreadyPublishedError(
                    f"{record} already holds a different report; a published experiment is "
                    "immutable, so new evidence needs a new declaration"
                )
            self._write_markdown(report)
            return PublishOutcome.UNCHANGED
        self._root.mkdir(parents=True, exist_ok=True)
        self._write_markdown(report)
        record.write_text(
            text, encoding="utf-8"
        )  # the record last: its existence means "published"
        return PublishOutcome.WRITTEN

    def rebuild_index(self) -> int:
        documents = [
            json.loads(path.read_text(encoding="utf-8"))
            for path in sorted(self._root.glob("EXP-*.json"))
        ]
        rows = self._index.rows(documents)
        self._root.mkdir(parents=True, exist_ok=True)
        (self._root / INDEX_JSON).write_text(_json_text({"experiments": rows}), encoding="utf-8")
        (self._root / INDEX_MARKDOWN).write_text(self._index.markdown(rows), encoding="utf-8")
        return len(rows)

    def _write_markdown(self, report: ExperimentReport) -> None:
        path = self._root / f"{report.experiment_id}.md"
        text = self._document.markdown(report)
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
